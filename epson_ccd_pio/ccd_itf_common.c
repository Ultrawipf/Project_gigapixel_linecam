int set_clock(const SM_def *smdef,int enable){
    if(smdef->sm == 255){
        return 0;
    }
    if(enable){
        pio_sm_set_enabled(smdef->pio, smdef->sm, true); // Enable SM
        gpio_put(RESETPIN, true); // Disable reset
        return 1;
    }else{
        pio_sm_set_enabled(smdef->pio, smdef->sm, false); // Disable SM
        pio_sm_set_pins(smdef->pio, smdef->sm, 0);  // Disable pins
        gpio_put(RESETPIN, false); // Hold under reset when clock off
        return 1;
    }
}


bool setup_clock(SM_def *smdef,float freq, uint gpio){
    // uint gpio = 4;
    smdef->sm = pio_claim_unused_sm(smdef->pio, true);

    smdef->offset = pio_add_program(smdef->pio, &ccdclock_program);
    // printf("Loaded ccd clock at %d, using sm %d, gpio %d\n", smdef->offset, smdef->sm, gpio);

    pio_sm_clear_fifos(smdef->pio, smdef->offset);

    ccdclock_program_init(smdef->pio, smdef->sm, smdef->offset, gpio, freq); // Generate 6MHz clock 6000000.0
    //gpio_set_drive_strength(gpio,GPIO_DRIVE_STRENGTH_8MA); // Tune clock
    return true;
}

bool setup_data(SM_def *smdef,uint gpiobase){

    if(smdef->sm == SMDEF_INVALID_VAL){
        smdef->sm = pio_claim_unused_sm(smdef->pio, true);
    }
    #ifdef PIOLIB
    pio_sm_config_xfer(smdef->pio, smdef->sm, PIO_DIR_FROM_SM, TRANSFERSIZE*4, 2);
    #endif
    if(smdef->offset == SMDEF_INVALID_VAL){
        smdef->offset = pio_add_program(smdef->pio, &ccddata_program);
    }
    
    // printf("Loaded ccd data at %d, using sm %d, gpio %d\n", smdef->offset, smdef->sm, gpiobase);
    ccddata_program_init(smdef->pio, smdef->sm, smdef->offset, gpiobase, PIODATACLOCK); // 60000000
    if(ACLKPIN != gpiobase+8){ // If clock out is not the same pin as clock in initialize clock in here
        pio_gpio_init(smdef->pio, gpiobase+8);
    }
    
    pio_sm_clear_fifos(smdef->pio, smdef->sm);
    return true;
}

uint32_t readData(const SM_def *smdef, uint32_t* buf,int samples){
    // Maybe clear buffer, reset and wait for TG using exec command?
    if(smdef->sm == SMDEF_INVALID_VAL){
        return 0;
    }
    
    uint32_t ret = 0;
    int ofs = 0;
    uint32_t curlen = 1;
    // printf("Waiting for %d samples\n",samples);
    while(ofs < samples){
        #ifdef PIOLIB
        curlen = MIN(samples-ofs,TRANSFERSIZE);
        ret = pio_sm_xfer_data(smdef->pio, smdef->sm, PIO_DIR_FROM_SM, curlen*sizeof(uint32_t), buf+ofs);
        if(ret){
            printf("pio sm xfer err %d\n",ret);
        }
        #else
        buf[ofs] = pio_sm_get_blocking(smdef->pio, smdef->sm);
        #endif
        ofs += curlen;
    }
    
    // pio_sm_set_enabled(pio, sm_data, false); // Disable SM
    if(ret){
        // printf("Transfer failed %d\n",ret);
        return 0;
    }
    return ofs;
}

void begin_ctrl_data_transfer(const SM_def *smdef,uint32_t basepin){
    pio_sm_set_enabled(smdef->pio,smdef->sm,false); // Turn off SM
    pio_sm_set_consecutive_pindirs(smdef->pio, smdef->sm, basepin+6, 2, true); // Set pins to output
    pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 0)); // Clock low
    sleep_us(100);
    gpio_put(CSPIN, false); // Assert CS
    sleep_us(100);
}

void end_ctrl_data_transfer(const SM_def *smdef,uint32_t basepin){
    pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 0)); // Both low
    pio_sm_set_consecutive_pindirs(smdef->pio, smdef->sm, basepin+6, 2, false); // Set pindirs back
    gpio_put(CSPIN, true); // Release CS
    sleep_us(DATA_BIT_DELAY_US*2);
}


/**
 * @brief Reads a 16b value via the DIO data interface
 * 
 * @param cmd Command/Register address, 0x80 R/W bit will be set
 * @return uint16_t Register contents
 */
uint16_t read_ctrl_data_sm(const SM_def *smdef,uint8_t cmd){
    const uint basepin = DATABASEPIN;
    uint16_t buf = 0;
    cmd |= 0x80; // Set read bit
    begin_ctrl_data_transfer(smdef,basepin);
    for(uint32_t count = 0; count < 8; count++){
        uint8_t curbit = (cmd >> (7-count) ) & 0x01; // Shift MSB
        pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | curbit)); // Clock low
        sleep_us(DATA_BIT_DELAY_US);
        pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 2 | curbit)); // Clock high
        sleep_us(DATA_BIT_DELAY_US);
    }
    pio_sm_set_consecutive_pindirs(smdef->pio, smdef->sm, basepin+6, 1, false); // Set data to input
    for(uint32_t count = 0; count < 16; count++){
        // uint8_t curbit = (cmd >> (7-count) ) & 0x01; // Shift MSB
        pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 0)); // Clock low
        sleep_us(DATA_BIT_DELAY_US);
        pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 2)); // Clock high
        bool dstate = gpio_get(basepin+6);
        if(dstate){
            buf |= 1 << (15-count);
        }
        sleep_us(DATA_BIT_DELAY_US);
    }
    end_ctrl_data_transfer(smdef,basepin);
    return buf;
}

/*
Abused data state machine to send control data in software. Speed is very slow so this is fine
Requires D6 and D7 to be set as SET pins
*/
void send_ctrl_data_sm_32(const SM_def *smdef,uint32_t buf){
    const uint basepin = DATABASEPIN;
    if(buf & 0x80000000){
        return; // Reject if read bit is set. Use read function instead
    }
    begin_ctrl_data_transfer(smdef,basepin);
    
    for(uint32_t count = 0; count < 24; count++){
        #ifdef CTRL_LSBFIRST
        uint8_t curbit = (buf >> (count) ) & 0x01; // Shift
        #else
        uint8_t curbit = (buf >> (23-count) ) & 0x01; // Shift MSB
        #endif
        pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 0 |curbit)); // Clock low
        sleep_us(DATA_BIT_DELAY_US);
        pio_sm_exec(smdef->pio, smdef->sm, (PIOSETINST | 2 | curbit)); // Clock high
        sleep_us(DATA_BIT_DELAY_US);
    }
    end_ctrl_data_transfer(smdef,basepin);
}
void send_ctrl_data_sm(const SM_def *sm_data,uint8_t cmd,uint8_t data1,uint8_t data2){
    uint32_t buf = (cmd << 16) | (data1<<8) | data2;
    send_ctrl_data_sm_32(sm_data,buf);
}

void send_ctrl_data_arr(const SM_def *sm_data,const uint32_t* buf,uint32_t len){
    for(uint32_t i = 0; i<len; i++){
        send_ctrl_data_sm_32(sm_data,buf[i]);
    }
}

/*Starts outputting frame data*/
void start_sampling(const SM_def *sm_data){
    // printf("Start sampling\n");
    pio_sm_clear_fifos(sm_data->pio, sm_data->sm);
    send_ctrl_data_arr(sm_data,block2,sizeof(block2)/sizeof(uint32_t)); // Seems to be sent before sampling starts
    send_ctrl_data_sm_32(sm_data,0x600081); // Start sampling
    // pio_sm_clkdiv_restart(sm_data.pio,sm_data.sm);
    pio_sm_set_enabled(sm_data->pio, sm_data->sm,true); // Turn on SM
}
/*Stops outputting frame data*/
void stop_sampling(const SM_def *sm_data){
    pio_sm_set_enabled(sm_data->pio, sm_data->sm,false); // Turn off SM
    send_ctrl_data_sm_32(sm_data,0x600080); // Stop sampling
    // printf("Stopped sampling\n");
}

/**
 * @brief Changes the line resolution
 * 
 * @param resPreset Resolution preset identifier
 */
void set_resolution(const SM_def *sm_data,CCD_Resolution_t resPreset){

    switch(resPreset){
        case CCD_Res_Full: // Main+Sub x2
        send_ctrl_data_arr(sm_data,setupCmds_4800dpi,sizeof(setupCmds_4800dpi)/sizeof(uint32_t));// Set 4800
        return; // Full width valid
        case CCD_Res_div2: // Main+Sub x1
        send_ctrl_data_arr(sm_data,setupCmds_2400dpi,sizeof(setupCmds_2400dpi)/sizeof(uint32_t));// Set 2400
        return;
        case CCD_Res_div4: // Main only
        send_ctrl_data_arr(sm_data,setupCmds_1200dpi,sizeof(setupCmds_1200dpi)/sizeof(uint32_t));// Set 1200
        return;
        case CCD_Res_div8: // Main w. skip
        send_ctrl_data_arr(sm_data,setupCmds_600dpi,sizeof(setupCmds_600dpi)/sizeof(uint32_t));// Set 600
        return;
        case CCD_Res_div16: // Mainw. skip
        send_ctrl_data_arr(sm_data,setupCmds_300dpi,sizeof(setupCmds_300dpi)/sizeof(uint32_t));// Set 300
        return;
    }
}

