/**
 * @brief Set the rgb gain ofs object
 * 
 * @param rOfs Red offset. 0x80 default
 * @param gOfs Green offset. 0x80 default
 * @param bOfs Blue offset. 0x80 default
 * @param rGain Red gain 6b
 * @param gGain Green gain 6b
 * @param bGain Blue gain 6b
 */
void set_rgb_gain_ofs(const SM_def *sm_data,uint8_t rOfs,uint8_t gOfs,uint8_t bOfs,uint8_t rGain,uint8_t gGain,uint8_t bGain){
    uint32_t dat = 0x780000;
    dat |= (rOfs & 0xff) << 8;
    dat |= (rGain & 0x3f);
    send_ctrl_data_sm_32(sm_data,dat);
    send_ctrl_data_arr(sm_data,block1,sizeof(block1)/sizeof(uint32_t));
    dat = 0x790000;
    dat |= (gOfs & 0xff) << 8;
    dat |= (gGain & 0x3f);
    send_ctrl_data_sm_32(sm_data,dat);
    send_ctrl_data_arr(sm_data,block1,sizeof(block1)/sizeof(uint32_t));
    dat = 0x7A0000;
    dat |= (bOfs & 0xff) << 8;
    dat |= (bGain & 0x3f);
    send_ctrl_data_sm_32(sm_data,dat);
    send_ctrl_data_arr(sm_data,block1,sizeof(block1)/sizeof(uint32_t));
}
